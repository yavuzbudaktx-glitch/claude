export type IconName = keyof typeof ICONS;

export default function PixelIcon({ name, size = 16, color = "currentColor", className = "" }: { name: IconName; size?: number; color?: string; className?: string }) {
  const grid = ICONS[name];
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" className={className} shapeRendering="crispEdges" aria-hidden="true">
      {grid.flatMap((row, y) => [...row].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} /> : null)))}
    </svg>
  );
}
