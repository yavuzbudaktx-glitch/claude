/** 20×20 Habbo-style badge. Unearned badges render as a dark silhouette. */
export function renderBadge(b: BadgeDef, earned: boolean): Raster {
  const base = earned ? FAMILY[b.family] : "#3a3f52";
  const r = new Raster(20, 20);
  const shape = [
    ".....##########.....",
    "...##..........##...",
    "..#..............#..",
    ".#................#.",
    ".#................#.",
    "#..................#",
    "#..................#",
    "#..................#",
    "#..................#",
    "#..................#",
    "#..................#",
    "#..................#",
    "#..................#",
    ".#................#.",
    ".#................#.",
    "..#..............#..",
    "...##..........##...",
    ".....##########.....",
  ];
  shape.forEach((row, y) => {
    const first = row.indexOf("#"), last = row.lastIndexOf("#");
    for (let x = 0; x < 20; x++) {
      if (row[x] === "#") r.set(x, y + 1, "#15121c");
      else if (x > first && x < last) {
        const c = y < 5 ? shade(base, 0.25) : y > 13 ? shade(base, -0.25) : base;
        r.set(x, y + 1, c);
      }
    }
  });
  const glyphColor = earned ? (b.family === "wake" || b.family === "general" ? "#fff6c8" : "#ffffff") : "#555b70";
  paintGrid(r, GLYPHS[b.glyph].map((row) => row.replace(/#/g, "G")), { G: glyphColor }, 5, 5);
  if (earned) {
    r.set(4, 3, "#ffffff");
    r.set(5, 3, "#ffffff");
    r.set(3, 4, "#ffffff");
  }
  return r;
}
